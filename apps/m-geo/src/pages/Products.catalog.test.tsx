import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react';
import {afterEach,expect,it,vi} from 'vitest';
import {setTestTransport} from '../api';
import type {Fact,Payload,Product,WorkspaceSnapshot} from '../types';
import Products from './Products';
afterEach(()=>{cleanup();setTestTransport(undefined)});
it('keeps historical catalog facts visible and unchanged until explicit removal then saves the repair',async()=>{
 const legacy:Fact={id:'catalog:legacyCode',label:'Legacy code',value:'FICTIONAL-LEGACY',source:'Fictional legacy record',visibility:'private',validUntil:'2099-01-01'};
 const known:Fact={id:'catalog:brand',label:'品牌',value:'虚构品牌',source:'Fictional source',visibility:'public',validUntil:null};
 const product:Product={id:'p',brandId:'b',name:'虚构历史商品',sku:'LEGACY-1',category:'',officialUrl:'',sourceText:'',privateNotes:'',facts:[legacy,known],revision:7,confirmedAt:'2026-10-23T00:00:00Z',updatedAt:''};
 const data:WorkspaceSnapshot={products:[product],questions:[],drafts:[],publications:[],observations:[]};
 const payloads:Payload[]=[];
 setTestTransport(async <T,>(action:string,p:Payload)=>{if(action==='product.save'){payloads.push(p);return {...product,...p,revision:8,confirmedAt:null} as T}throw Error(action)});
 render(<Products brand={{id:'b',name:'虚构品牌',createdAt:''}} data={data} refresh={vi.fn(async()=>{})}/>);
 fireEvent.click(screen.getByRole('button',{name:/虚构历史商品/}));
 expect(screen.getByDisplayValue('FICTIONAL-LEGACY')).toBeVisible();
 expect(screen.getByDisplayValue('Fictional legacy record')).toBeVisible();
 expect(screen.getByLabelText('事实 1 公开范围')).toHaveValue('private');
 expect(screen.getByText(/历史渠道字段/)).toBeVisible();
 expect(screen.getByLabelText('渠道身份 · 品牌')).toHaveValue('虚构品牌');
 expect(screen.queryByLabelText('事实 2 内容')).not.toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:'保存商品'}));
 await waitFor(()=>expect(payloads).toHaveLength(1));
 expect(payloads[0].facts).toEqual([legacy,known]);
 await screen.findByText('商品已保存，请重新核对并确认事实');
 fireEvent.click(screen.getByRole('button',{name:'删除事实 1'}));
 expect(screen.queryByDisplayValue('FICTIONAL-LEGACY')).not.toBeInTheDocument();
 expect(screen.getByRole('button',{name:'确认已保存的事实'})).toBeDisabled();
 fireEvent.click(screen.getByRole('button',{name:'保存商品'}));
 await waitFor(()=>expect(payloads).toHaveLength(2));
 expect(payloads[1].facts).toEqual([known]);
 expect(payloads[1]).toMatchObject({id:'p',expectedRevision:7});
});
